// Helper functions
export const getProductDetailData = async (categorySlug, productSlug, detailSlug) => {
  await new Promise(resolve => setTimeout(resolve, 50));

  if (!productDetailData[categorySlug]) {
    return null;
  }

  if (!productDetailData[categorySlug][productSlug]) {
    return null;
  }

  const data = productDetailData[categorySlug][productSlug][detailSlug];

  if (!data) {
    return null;
  }

  return {
    ...data,
    breadcrumbs: generateDetailBreadcrumbs(categorySlug, productSlug, data.title, detailSlug)
  };
};

export const getAllProductDetailSlugs = (categorySlug, productSlug) => {
  if (!productDetailData[categorySlug]) {
    return [];
  }

  if (!productDetailData[categorySlug][productSlug]) {
    return [];
  }

  return Object.keys(productDetailData[categorySlug][productSlug]);
};

// Helper function for categories with direct detail pages (no listing page)
// Used for food-packaging where URL is /food-packaging/[productSlug]
export const getDirectDetailData = async (categorySlug, productSlug) => {
  await new Promise(resolve => setTimeout(resolve, 50));

  if (!productDetailData[categorySlug]) {
    return null;
  }

  const data = productDetailData[categorySlug][productSlug];

  if (!data || !data.title) {
    return null;
  }

  return {
    ...data,
    breadcrumbs: [
      { label: 'Home', href: '/' },
      { label: getCategoryName(categorySlug), href: `/${categorySlug}` },
      { label: data.title, href: `/${categorySlug}/${productSlug}` }
    ]
  };
};

// Get all direct detail slugs for a category (for categories without listing pages)
export const getAllDirectDetailSlugs = (categorySlug) => {
  if (!productDetailData[categorySlug]) {
    return [];
  }

  return Object.keys(productDetailData[categorySlug]);
};
